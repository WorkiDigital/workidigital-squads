#!/usr/bin/env python3
"""Generate project-scoped Codex custom agents from the reviewed Worki roster."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import tomllib


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "worki/codex-agents.json"
SQUAD_PATH = ROOT / "worki/squad.json"


def read_text(relative: str) -> str:
    path = ROOT / relative
    if not path.is_file():
        raise FileNotFoundError(f"Fonte ausente: {relative}")
    resolved = path.resolve()
    if not resolved.is_relative_to(ROOT.resolve()):
        raise ValueError(f"Fonte fora do repositório: {relative}")
    return path.read_text(encoding="utf-8")


def body(markdown: str) -> str:
    if not markdown.startswith("---\n"):
        return markdown.strip()
    end = markdown.find("\n---\n", 4)
    if end == -1:
        raise ValueError("Frontmatter sem fechamento")
    return markdown[end + 5 :].strip()


def toml_string(value: str) -> str:
    # JSON strings are valid TOML basic strings for the characters emitted here.
    return json.dumps(value, ensure_ascii=False)


def render(name: str, description: str, sources: list[str], skill: str | None) -> str:
    sections = [
        "# Contrato Worki\n\n" + read_text("AGENTS.md").strip(),
        "# Política operacional\n\n" + read_text("docs/politica-worki.md").strip(),
    ]
    for source in sources:
        sections.append(f"# Competência importada de `{source}`\n\n{body(read_text(source))}")
    if skill:
        sections.append(f"# Skill da etapa `{skill}`\n\n{body(read_text(skill))}")
    sections.append(
        "# Proveniência e licença\n\n"
        "Competências adaptadas de msitarzewski/agency-agents no commit "
        "652b2692f8d8ec2b1f1a38e559073e287dfdc469. Leia LICENSE e "
        "THIRD_PARTY_NOTICES.md. As restrições Worki prevalecem sobre exemplos "
        "de autonomia, comandos e metas presentes nas fontes importadas."
    )
    instructions = "\n\n".join(sections) + "\n"
    output = (
        "# Generated by scripts/generate_codex_agents.py — do not edit manually.\n"
        f"name = {toml_string(name)}\n"
        f"description = {toml_string(description)}\n"
        f"developer_instructions = {toml_string(instructions)}\n"
    )
    tomllib.loads(output)
    return output


def build(check: bool = False) -> list[Path]:
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    squad = json.loads(SQUAD_PATH.read_text(encoding="utf-8"))
    stages = {stage["id"]: stage for stage in squad["stages"]}
    output_dir = ROOT / manifest["output_dir"]
    expected: dict[Path, str] = {}

    orchestrator = manifest["orchestrator"]
    expected[output_dir / f'{orchestrator["slug"]}.toml'] = render(
        orchestrator["name"], orchestrator["description"], orchestrator["sources"], None
    )

    for agent in manifest["agents"]:
        stage = stages[agent["stage"]]
        expected[output_dir / f'{agent["slug"]}.toml'] = render(
            agent["name"], agent["description"], stage["agents"], stage["skill"]
        )

    existing = set(output_dir.glob("*.toml")) if output_dir.exists() else set()
    unexpected = existing - set(expected)
    if unexpected:
        raise ValueError("Agentes TOML inesperados: " + ", ".join(str(p) for p in sorted(unexpected)))

    if check:
        drift = [path for path, content in expected.items() if not path.is_file() or path.read_text(encoding="utf-8") != content]
        if drift:
            raise ValueError("Agentes ausentes ou desatualizados: " + ", ".join(str(p) for p in drift))
        return sorted(expected)

    output_dir.mkdir(parents=True, exist_ok=True)
    for path, content in expected.items():
        path.write_text(content, encoding="utf-8")
    return sorted(expected)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when generated files are missing or stale")
    args = parser.parse_args()
    paths = build(check=args.check)
    verb = "validated" if args.check else "generated"
    print(f"PASS: {len(paths)} Codex agents {verb} in .codex/agents/")
    for path in paths:
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
